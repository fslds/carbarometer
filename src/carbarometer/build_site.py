"""Bundle the site's ES modules into one classic script so index.html also works from file://.

Browsers refuse ES modules and fetch() on file:// URLs. This wraps every module in site/js/ in a
function, rewrites its imports/exports to a tiny require table, and writes site/app.bundle.js.
The data is embedded as site/data/barometer.js (window.CB_DATA) for the same reason.

Supported syntax (all the site uses): `import { a, b as c } from "./x.js"`, `import * as x from "./x.js"`,
`export function|async function|const|let|class name`, and `export { a, b }`.
"""

from __future__ import annotations

import json
import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "site"
DIST = ROOT / "dist"
ENTRY = "js/app.js"
# The artifact build loads ECharts from an allowed CDN instead of the vendored copy (same 5.6 API).
ECHARTS_CDN = "https://cdnjs.cloudflare.com/ajax/libs/echarts/5.6.0/echarts.min.js"

IMPORT = re.compile(r'^import\s+(?:\{([^}]*)\}|\*\s+as\s+(\w+))\s+from\s+"([^"]+)";?\s*$', re.M)
EXPORT_DECL = re.compile(r"^export\s+((?:async\s+)?function\*?|const|let|class)\s+(\w+)", re.M)
EXPORT_LIST = re.compile(r"^export\s+\{([^}]*)\};?\s*$", re.M)


def transform(path: str, src: str) -> str:
    base = posixpath.dirname(path)
    exports: list[str] = []

    def imp(m: re.Match) -> str:
        names, star, spec = m.groups()
        target = posixpath.normpath(posixpath.join(base, spec))
        if star:
            return f'const {star} = __req("{target}");'
        parts = [n.strip() for n in names.split(",") if n.strip()]
        binds = [": ".join(p.split(" as ")) if " as " in p else p for p in parts]
        return f'const {{ {", ".join(binds)} }} = __req("{target}");'

    def decl(m: re.Match) -> str:
        exports.append(m.group(2))
        return f"{m.group(1)} {m.group(2)}"

    def lst(m: re.Match) -> str:
        exports.extend(n.strip() for n in m.group(1).split(",") if n.strip())
        return ""

    src = IMPORT.sub(imp, src)
    src = EXPORT_DECL.sub(decl, src)
    src = EXPORT_LIST.sub(lst, src)
    if re.search(r"^\s*(import|export)\s", src, re.M):
        raise SystemExit(f"{path}: unsupported import/export syntax left after bundling")
    return f'__def("{path}", function () {{\n{src}\nreturn {{ {", ".join(dict.fromkeys(exports))} }};\n}});\n'


def build() -> None:
    modules = sorted(p.relative_to(SITE).as_posix() for p in (SITE / "js").rglob("*.js"))
    out = [
        "// Generated by `uv run carbarometer-build` from site/js/*.js. Do not edit.\n",
        "(function () {\n'use strict';\n",
        "const __defs = {}, __cache = {};\n",
        "function __def(name, fn) { __defs[name] = fn; }\n",
        "function __req(name) {\n"
        "  if (!(name in __cache)) { if (!__defs[name]) throw new Error('module not found: ' + name); __cache[name] = __defs[name](); }\n"
        "  return __cache[name];\n}\n",
    ]
    for m in modules:
        out.append(transform(m, (SITE / m).read_text("utf-8")))
    out.append(f'__req("{ENTRY}");\n}})();\n')
    (SITE / "app.bundle.js").write_text("".join(out), "utf-8")

    data = SITE / "data" / "barometer.json"
    if data.exists():
        payload = json.dumps(json.loads(data.read_text("utf-8")), ensure_ascii=False, separators=(",", ":"))
        (SITE / "data" / "barometer.js").write_text(f"window.CB_DATA={payload};\n", "utf-8")
    print(f"bundled {len(modules)} modules into site/app.bundle.js", file=sys.stderr)


def inline_script(js: str) -> str:
    if "</script" in js.lower():
        js = re.sub(r"</(script)", r"<\\/\1", js, flags=re.I)
    return f"<script>\n{js}</script>\n"


def build_artifact() -> Path:
    """Single self-contained page for publishing as a claude.ai artifact (dist/car-barometer.html).

    The artifact host supplies the <html>/<head>/<body> skeleton and only allows scripts from a few CDNs,
    so this inlines the CSS, data and bundle and writes just the page content. It also leaves out the
    stored-theme bootstrap so the viewer's own theme setting wins.
    """
    index = (SITE / "index.html").read_text("utf-8")
    title = re.search(r"<title>.*?</title>", index, re.S).group(0)
    body = re.search(r"<body>(.*)</body>", index, re.S).group(1).strip()
    css = (SITE / "css" / "app.css").read_text("utf-8")
    data = (SITE / "data" / "barometer.js").read_text("utf-8")
    bundle = (SITE / "app.bundle.js").read_text("utf-8")
    page = (
        f"{title}\n<style>\n{css}</style>\n{body}\n"
        f'<script src="{ECHARTS_CDN}"></script>\n'
        + inline_script(data)
        + inline_script(bundle)
    )
    DIST.mkdir(exist_ok=True)
    out = DIST / "car-barometer.html"
    out.write_text(page, "utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(page.encode()) // 1024} KB)", file=sys.stderr)
    return out


def main() -> None:
    build()
    if "--artifact" in sys.argv:
        build_artifact()


if __name__ == "__main__":
    main()
